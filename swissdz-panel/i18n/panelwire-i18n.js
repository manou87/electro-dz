  function edzCatLabel(cat) {
    if (cat == null || cat === "") return cat;
    var lang = getLang();
    var s = String(cat);
    if (lang === "fr" && EDZ_CATS_FR[s]) return EDZ_CATS_FR[s];
    return s;
  }
  function edzTranslate(raw) {
    if (raw == null || raw === "") return raw;
    var s = String(raw);
    var lang = getLang();
    if (lang === "fr") {
      if (Object.prototype.hasOwnProperty.call(EDZ_VAL_FR, s)) return EDZ_VAL_FR[s];
      return s;
    }
    if (Object.prototype.hasOwnProperty.call(EDZ_VAL_EN, s)) return EDZ_VAL_EN[s];
    return s;
  }

  function normalizeLang(raw) {
    var s = String(raw || "").toLowerCase();
    if (s.indexOf("en") === 0) return "en";
    return "fr";
  }
  function getLang() {
    try {
      var saved = localStorage.getItem(LANG_KEY);
      if (saved) return normalizeLang(saved);
    } catch (_) {}
    return "fr";
  }
  function setLang(lang) {
    lang = normalizeLang(lang);
    try { localStorage.setItem(LANG_KEY, lang); } catch (_) {}
    return lang;
  }
  function t(key, vars) {
    var lang = getLang();
    var pack = STRINGS[lang] || STRINGS.fr;
    var s = (pack && pack[key] != null) ? pack[key] : ((STRINGS.fr && STRINGS.fr[key]) || key);
    if (vars && typeof s === "string") {
      Object.keys(vars).forEach(function (k) {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return s;
  }
  function catLabel(cat) {
    var lang = getLang();
    var pack = CATS[lang] || CATS.fr;
    return (pack && pack[cat]) || cat;
  }
  function colorLabel(frName) {
    var lang = getLang();
    var pack = COLORS[lang] || COLORS.fr;
    return (pack && pack[frName]) || frName;
  }
  function componentName(id, def) {
    if (!def) return id || "";
    var lang = getLang();
    var isEdz = String(id || "").indexOf("edz_") === 0;
    if (lang === "en") {
      if (def.nameEn) return def.nameEn;
      if (SWISS_EN[id]) return SWISS_EN[id];
      return def.name || id;
    }
    /* fr */
    if (def.nameFr) return def.nameFr;
    if (isEdz && EDZ_FR[id]) return EDZ_FR[id];
    return def.name || id;
  }
  function applyStaticDom() {
    var lang = getLang();
    try { document.documentElement.lang = lang; } catch (_) {}
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (!key) return;
      var html = el.getAttribute("data-i18n-html") === "1";
      if (html) el.innerHTML = t(key);
      else el.textContent = t(key);
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    var btn = document.getElementById("btnLang");
    if (btn) {
      btn.textContent = lang === "en" ? "EN" : "FR";
      btn.setAttribute("aria-expanded", "false");
      btn.title = t("langTitle");
      btn.setAttribute("aria-label", t("langAria"));
      btn.dataset.lang = lang;
    }
    var menu = document.getElementById("langMenu");
    if (menu) menu.classList.remove("open");
    document.querySelectorAll("#langDropdown [data-set-lang]").forEach(function (opt) {
      var code = opt.getAttribute("data-set-lang");
      opt.setAttribute("aria-selected", code === lang ? "true" : "false");
      if (code === "fr") opt.textContent = t("langFr");
      else if (code === "en") opt.textContent = t("langEn");
    });
  }

