  function normalizeLang(lang, fallback) {
    if (lang === "fr" || lang === "ar" || lang === "en") return lang;
    return fallback || "ar";
  }

  var defaultLang = normalizeLang(
    document.documentElement.getAttribute("data-default-lang") || "ar",
    "ar"
  );

  function applyLang(lang) {
    lang = normalizeLang(lang, defaultLang);
    if (!T[lang]) lang = defaultLang;
    var root = document.documentElement;
    root.lang = lang;
    root.dir = lang === "ar" ? "rtl" : "ltr";
    document.title = T[lang]["meta.title"];

    var desc = document.querySelector('meta[name="description"]');
    if (desc && T[lang]["meta.description"]) {
      desc.setAttribute("content", T[lang]["meta.description"]);
    }
    var ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.setAttribute("content", T[lang]["meta.title"]);
    var ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc && T[lang]["meta.description"]) {
      ogDesc.setAttribute("content", T[lang]["meta.description"]);
    }
    var twTitle = document.querySelector('meta[name="twitter:title"]');
    if (twTitle) twTitle.setAttribute("content", T[lang]["meta.title"]);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (T[lang][key] !== undefined) el.textContent = T[lang][key];
    });

    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (T[lang][key] !== undefined) el.setAttribute("aria-label", T[lang][key]);
    });

    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });

    try {
      localStorage.setItem("electrodz-site-lang", lang);
    } catch (e) {}
  }

  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    btn.addEventListener("click", function () {
      applyLang(btn.getAttribute("data-lang"));
    });
  });

  var saved = defaultLang;
  try {
    saved = localStorage.getItem("electrodz-site-lang") || defaultLang;
  } catch (e) {}
  saved = normalizeLang(saved, defaultLang);
  applyLang(saved);

  window.ElectroDzAccueilI18n = { applyLang: applyLang, t: function (lang, key) {
    return T[lang] && T[lang][key] !== undefined ? T[lang][key] : key;
  }};
